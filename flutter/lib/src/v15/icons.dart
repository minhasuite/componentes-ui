/// Ícones por nome do conjunto da suíte. `Icon(SsIcons.named('credit-card'))`.
/// Aceita o nome da v1 e o da v2 do Heroicons ("magnifying-glass" vale
/// "search"); o que não existe vira [fallback] (a tela nunca quebra por um
/// nome salvo no banco). [solid] usa a versão cheia quando há.
abstract final class SsIcons {
  /// Ícone de reserva (o "question-mark-circle" do web).
  static const fallback = Icons.help_outline_rounded;

  /// Os nomes do conjunto (os mesmos da gem), sem os apelidos.
  static List<String> get names => _ssIconNames;

  /// Apelidos (v2 → v1).
  static Map<String, String> get aliases => _ssIconAliases;

  /// O nome no conjunto (resolve o apelido), ou nulo se não existe.
  static String? resolve(String? name) {
    if (name == null) return null;
    var n = name.trim().toLowerCase().replaceAll('_', '-');
    if (n.startsWith('heroicon-')) n = n.substring(9);
    n = _ssIconAliases[n] ?? n;
    return _material.containsKey(n) ? n : null;
  }

  static bool has(String? name) => resolve(name) != null;

  static IconData named(String? name, {bool solid = false}) {
    final n = resolve(name);
    if (n == null) return fallback;
    if (solid && _ssIconSolid.contains(n)) return _solid[n] ?? _material[n]!;
    return _material[n]!;
  }
}

